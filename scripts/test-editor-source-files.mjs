import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, readdir, rename, rm, symlink, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createEditorSourceFile, getEditorSourceFileChoices, planEditorSourceFileCreation, readSiteFileTree } from './lib/editor-site-tree.mjs';

const temporary = await mkdtemp(path.join(os.tmpdir(), 'norna-source-files-'));
const siteRoot = path.join(temporary, 'site');
const write = async (relative, text) => {
	const filename = path.join(siteRoot, relative);
	await mkdir(path.dirname(filename), { recursive: true }); await writeFile(filename, text);
};
const choices = (directory = siteRoot) => getEditorSourceFileChoices({ siteRoot, directory });
const plan = (relative, value, directory = siteRoot) => planEditorSourceFileCreation({ siteRoot, directory, filename: path.join(siteRoot, relative), value });
const tree = (sources) => readSiteFileTree({ siteRoot, editing: true, sources });
const find = (snapshot, relative, kind) => snapshot.items.find((item) => item.sourcePath === path.join(siteRoot, relative) && (!kind || item.kind === kind));
try {
	await mkdir(siteRoot);
	assert.deepEqual((await choices()).map((entry) => entry.name), ['content.md', 'site-config/settings.yaml', 'site-config/site-theme.yaml', 'site-config/shared-content.yaml']);
	let view = await tree();
	assert.equal(view.items[0].kind, 'incomplete');
	assert.equal(view.items[0].isHome, true);
	assert.ok(view.items[0].issues.some((issue) => /Homepage content.md is missing/.test(issue.message)));
	const home = await plan('content.md', 'Övningssajten');
	assert.deepEqual(await readdir(siteRoot), [], 'Planning must not create files.');
	await createEditorSourceFile(home);
	assert.equal(await readFile(home.filename, 'utf8'), '# Övningssajten\n');
	await assert.rejects(createEditorSourceFile(home), /already exists/);
	await assert.rejects(plan('site-config/settings.yaml', 'not a URL'), /invalid values/);
	const settings = await plan('site-config/settings.yaml', 'https://example.com/');
	assert.deepEqual(await readdir(siteRoot), ['content.md']);
	await createEditorSourceFile(settings);
	await createEditorSourceFile(await plan('site-config/site-theme.yaml'));
	await createEditorSourceFile(await plan('site-config/shared-content.yaml'));
	await write('public/robots.txt', 'User-agent: *\n');
	await createEditorSourceFile(await plan('theme.yaml'));
	assert.deepEqual(await choices(), []);
	view = await tree();
	assert.ok(view.items.every((item) => !item.issues?.length), JSON.stringify(view.items.filter((item) => item.issues?.length)));
	assert.equal(view.items.filter((item) => item.sourcePath === home.filename).length, 1, 'A page replaces its content file row.');
	assert.deepEqual(view.items.filter((item) => item.parentId === home.filename).map((item) => item.title), ['theme.yaml', 'site-config', 'public']);

	await write('pages/010-leaf/content.md', '# Leaf\n');
	await mkdir(path.join(siteRoot, 'pages/020-incomplete/pages/010-child'), { recursive: true });
	await write('pages/020-incomplete/pages/010-child/content.md', '# Visible child\n');
	const incomplete = path.join(siteRoot, 'pages/020-incomplete');
	assert.deepEqual((await choices(incomplete)).map((entry) => entry.name), ['content.md', 'category.yaml']);
	view = await tree();
	assert.equal(find(view, 'pages/020-incomplete/content.md').kind, 'incomplete');
	assert.equal(find(view, 'pages/020-incomplete/pages/010-child/content.md').title, 'Visible child');
	await createEditorSourceFile(await plan('pages/020-incomplete/category.yaml', 'Topics', incomplete));
	view = await tree();
	assert.equal(find(view, 'pages/020-incomplete/category.yaml', 'category').title, 'Topics');
	assert.ok(find(view, 'pages/020-incomplete/category.yaml', 'file'));
	assert.deepEqual((await choices(incomplete)).map((entry) => entry.name), ['theme.yaml']);

	await write('pages/010-leaf/settings.yaml', 'url: https://example.com/\n');
	await write('pages/010-leaf/notes.md', '# Author notes\n');
	await write('pages/010-leaf/theme.yaml', 'layout:\n  textWidth: invalid\n');
	await write('pages/010-leaf/misc/content.md', '# Misplaced\n');
	await write('public/content.md', 'A valid public download.\n');
	await write('public/.well-known/security.txt', 'Contact: mailto:security@example.com\n');
	await write('images', 'This should be a directory.');
	await write('.DS_Store', 'metadata'); await write('.norna/generated.txt', 'generated');
	await mkdir(path.join(siteRoot, 'pages/010-leaf/images'));
	await symlink(temporary, path.join(siteRoot, 'public/outside'));
	view = await tree();
	assert.equal(find(view, 'pages/010-leaf/settings.yaml').issues[0].severity, 'warning');
	assert.equal(find(view, 'pages/010-leaf/notes.md').note, 'Not used by Norna');
	assert.match(find(view, 'pages/010-leaf/theme.yaml').issues[0].message, /invalid values/);
	assert.equal(find(view, 'pages/010-leaf/misc/content.md').issues[0].severity, 'warning');
	assert.equal(find(view, 'public/content.md').issues, undefined);
	assert.ok(find(view, 'public/.well-known/security.txt'));
	assert.match(find(view, 'images').issues[0].message, /Expected a directory/);
	assert.equal(find(view, 'public/outside'), undefined);
	assert.equal(find(view, '.DS_Store'), undefined);
	assert.equal(find(view, '.norna/generated.txt'), undefined);
	assert.equal(find(view, 'pages/010-leaf/images').kind, 'directory');
	const themePath = path.join(siteRoot, 'pages/010-leaf/theme.yaml');
	view = await tree(new Map([[themePath, 'layout:\n  textWidth: normal\n']]));
	assert.equal(find(view, 'pages/010-leaf/theme.yaml').issues, undefined, 'Unsaved repair must replace disk diagnostics.');
	assert.match(await readFile(themePath, 'utf8'), /invalid/);
	await write('pages/010-leaf/category.yaml', 'label: Conflict\n');
	view = await tree();
	assert.ok(find(view, 'pages/010-leaf/category.yaml', 'category').issues.some((issue) => /Both/.test(issue.message)));
	assert.ok(find(view, 'pages/010-leaf/content.md', 'file'), 'A conflicting content file must stay visible.');
	assert.deepEqual(await choices(path.dirname(themePath)), [], 'Do not create more files in a conflicting entry.');

	await assert.rejects(getEditorSourceFileChoices({ siteRoot, directory: temporary }), /selected site/);
	await assert.rejects(choices(path.join(siteRoot, 'public')), /permitted location/);
	await write('pages/030-safe/content.md', '# Safe\n');
	const safe = path.join(siteRoot, 'pages/030-safe');
	const stale = await plan('pages/030-safe/theme.yaml', undefined, safe);
	await rename(safe, `${safe}-old`); await mkdir(safe); await write('pages/030-safe/content.md', '# Replacement\n');
	await assert.rejects(createEditorSourceFile(stale), /directory changed/);
	const race = await plan('pages/030-safe/theme.yaml', undefined, safe);
	await write('pages/030-safe/theme.yaml', 'keep my bytes');
	await assert.rejects(createEditorSourceFile(race), /already exists/);
	assert.equal(await readFile(race.filename, 'utf8'), 'keep my bytes');
	await rm(race.filename); await symlink(path.join(siteRoot, 'theme.yaml'), race.filename);
	assert.deepEqual(await choices(safe), [], 'An existing symlink must not be offered for replacement.');
	await rm(home.filename); await rm(path.join(siteRoot, 'site-config/settings.yaml'));
	view = await tree();
	assert.equal(view.items[0].kind, 'incomplete');
	assert.ok(find(view, 'pages/030-safe/content.md'), 'A broken root must retain its descendants.');
	assert.ok((await choices()).some((entry) => entry.name === 'content.md'));
	console.log('Source-file editing tests passed: projection, diagnostics, dirty repairs, missing sources, templates, cancellation, collisions, stale paths and symlink boundaries.');
} finally { await rm(temporary, { recursive: true, force: true }); }
