const keys = Object.freeze(Object.keys(reference));
const placeholderPattern = /\[([A-Z_]+)\]/g;
const placeholders = (value) => [...value.matchAll(placeholderPattern)].map((match) => match[1]).sort();
const define = (tag, values) => {
	const missing = keys.filter((key) => !Object.hasOwn(values, key));
	const unexpected = Object.keys(values).filter((key) => !Object.hasOwn(reference, key));
	if (missing.length > 0 || unexpected.length > 0) {
		throw new Error(`Pagefind translation ${tag} does not match its key contract.`);
	}
	for (const key of keys) {
		if (typeof values[key] !== 'string' || values[key].trim() === '') {
			throw new Error(`Pagefind translation ${tag}.${key} must be a non-empty string.`);
		}
		if (placeholders(values[key]).join('\0') !== placeholders(reference[key]).join('\0')) {
			throw new Error(`Pagefind translation ${tag}.${key} does not preserve its placeholders.`);
		}
	}
	return Object.freeze(values);
};

