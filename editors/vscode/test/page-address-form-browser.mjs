import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createRequire } from 'node:module';
import { chromium } from '@playwright/test';
const { pageFormHtml } = createRequire(import.meta.url)('../page-form.cjs');

test('Properties submits the chosen slug and alias policy through a separate action', async t => {
	const browser = await chromium.launch();
	t.after(() => browser.close());
	const page = await browser.newPage();
	const errors = [];
	page.on('pageerror', error => errors.push(error.message));
	await page.evaluate(() => {
		window.messages = [];
		window.acquireVsCodeApi = () => ({ postMessage: message => window.messages.push(message) });
	});
	await page.setContent(pageFormHtml({ edit: true, canChangeAddress: true, title: 'Guide', description: '', listed: true, listChildren: false, aliases: ['/old-guide/'], slug: 'guide', url: 'https://example.com/manual/guide/' }, 'test'));
	assert.equal(await page.locator('#slug').inputValue(), 'guide');
	assert.equal(await page.locator('#preserve-aliases').isChecked(), true);
	await page.locator('#slug').fill('handbook');
	await page.locator('#preserve-aliases').uncheck();
	await page.waitForFunction(() => window.messages.at(-1).values.slug === 'handbook' && window.messages.at(-1).values.preserveAliases === false);
	const last = await page.evaluate(() => window.messages.at(-1));
	assert.equal(last.type, 'preview');
	await page.locator('#change-address').click();
	let request = await page.evaluate(() => window.messages.at(-1));
	assert.equal(request.type, 'address');
	assert.equal(request.values.slug, 'handbook');
	assert.equal(request.values.preserveAliases, false);
	assert.deepEqual(request.values.aliases, ['/old-guide/']);
	assert.equal(await page.locator('#submit').isDisabled(), true);
	const reply = data => page.evaluate(data => window.dispatchEvent(new MessageEvent('message', { data })), data);
	await reply({ type: 'result', revision: request.revision, preview: 'Cancelled; no files changed.' });
	assert.equal(await page.locator('#change-address').isEnabled(), true);
	assert.equal(await page.locator('#preserve-aliases').isChecked(), false, 'Cancellation retains the choice.');
	await page.locator('#preserve-aliases').check();
	await page.locator('#change-address').focus();
	await page.keyboard.press('Enter');
	request = await page.evaluate(() => window.messages.at(-1));
	assert.equal(request.type, 'address');
	assert.equal(request.values.preserveAliases, true);
	await reply({ type: 'result', revision: request.revision, errors: { slug: 'The address is already taken.' } });
	assert.equal(await page.locator('#slug-error').textContent(), 'The address is already taken.');
	assert.equal(await page.locator('#slug').getAttribute('aria-invalid'), 'true');
	await page.locator('#slug').fill('guide');
	await page.locator('#title').fill('New title');
	await page.locator('#submit').click();
	assert.equal(await page.evaluate(() => window.messages.at(-1).type), 'submit');
	assert.deepEqual(errors, []);
});
